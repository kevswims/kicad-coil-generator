//! Phase assignment and winding-sense logic for a stator's coils.
//!
//! Pure logic, no KiCad dependency: given pole/coil counts, assigns each
//! coil to one of three phases and decides whether that coil's winding
//! needs to be reversed so same-phase coils reinforce rather than cancel,
//! then orders each phase's coils into a series chain.
//!
//! Algorithm (from `coil-generator-spec.md`): electrical angle = pole_pairs
//! × mechanical angle; each phase has a reference angle (the electrical
//! angle of that phase's first coil); a coil's sign flips if its own
//! electrical angle is more than 90° (mod 360°) from its phase's reference
//! — i.e. if winding it "forward" would produce flux opposing the phase's
//! reference coil instead of reinforcing it.

use std::f64::consts::PI;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Phase {
    A,
    B,
    C,
}

impl Phase {
    fn from_coil_index(coil_index: u32) -> Self {
        match coil_index % 3 {
            0 => Phase::A,
            1 => Phase::B,
            _ => Phase::C,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WindingSense {
    /// Wind the coil as generated by `coil_geometry`.
    Forward,
    /// Wind the coil with its leads swapped (electrically reversed) so its
    /// flux reinforces, rather than cancels, its phase's reference coil.
    Reversed,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CoilAssignment {
    pub coil_index: u32,
    pub phase: Phase,
    pub sense: WindingSense,
    /// Electrical angle in radians, normalized to [0, 2*PI).
    pub electrical_angle_rad: f64,
}

fn normalize_angle(angle_rad: f64) -> f64 {
    let two_pi = 2.0 * PI;
    let wrapped = angle_rad % two_pi;
    if wrapped < 0.0 {
        wrapped + two_pi
    } else {
        wrapped
    }
}

/// Shortest signed angular distance from `from` to `to`, in (-PI, PI].
fn angular_distance(from: f64, to: f64) -> f64 {
    let two_pi = 2.0 * PI;
    let raw = normalize_angle(to - from);
    if raw > PI {
        raw - two_pi
    } else {
        raw
    }
}

/// Mechanical angle of a coil, evenly spaced around the full circle — the
/// same convention as `coil_geometry::coil_center_angle_rad`.
fn mechanical_angle_rad(coil_index: u32, coils: u32) -> f64 {
    coil_index as f64 * 2.0 * PI / coils as f64
}

fn electrical_angle_rad(coil_index: u32, coils: u32, pole_pairs: u32) -> f64 {
    normalize_angle(mechanical_angle_rad(coil_index, coils) * pole_pairs as f64)
}

/// Assigns every coil in a `coils`-coil, `poles`-pole motor to a phase and a
/// winding sense.
///
/// `poles` must be even (a motor's pole count always is); coils need not be
/// a multiple of 3, but a balanced three-phase design uses one.
pub fn assign_coils(coils: u32, poles: u32) -> Vec<CoilAssignment> {
    let pole_pairs = poles / 2;

    let mut reference_angle: [Option<f64>; 3] = [None, None, None];

    (0..coils)
        .map(|coil_index| {
            let phase = Phase::from_coil_index(coil_index);
            let angle = electrical_angle_rad(coil_index, coils, pole_pairs);

            let phase_slot = match phase {
                Phase::A => 0,
                Phase::B => 1,
                Phase::C => 2,
            };
            let reference = *reference_angle[phase_slot].get_or_insert(angle);

            let sense = if angular_distance(reference, angle).abs() > PI / 2.0 {
                WindingSense::Reversed
            } else {
                WindingSense::Forward
            };

            CoilAssignment {
                coil_index,
                phase,
                sense,
                electrical_angle_rad: angle,
            }
        })
        .collect()
}

/// One phase's coils, in the order they should be wired in series.
#[derive(Debug, Clone, PartialEq)]
pub struct PhaseChain {
    pub phase: Phase,
    /// Coil indices in series order (this coil's exit lead connects to the
    /// next coil's entry lead; which physical lead is "entry" vs "exit" for
    /// a given coil depends on its `WindingSense`, decided in
    /// `assign_coils`).
    pub coil_order: Vec<u32>,
}

/// Groups a motor's coil assignments into per-phase series chains, in
/// ascending coil-index order within each phase (coil 1 out -> coil 4 in ->
/// coil 7 out -> ... for a coils=mod-3 layout, per the spec's algorithm).
pub fn build_phase_chains(assignments: &[CoilAssignment]) -> [PhaseChain; 3] {
    let mut a = Vec::new();
    let mut b = Vec::new();
    let mut c = Vec::new();

    for assignment in assignments {
        match assignment.phase {
            Phase::A => a.push(assignment.coil_index),
            Phase::B => b.push(assignment.coil_index),
            Phase::C => c.push(assignment.coil_index),
        }
    }

    [
        PhaseChain {
            phase: Phase::A,
            coil_order: a,
        },
        PhaseChain {
            phase: Phase::B,
            coil_order: b,
        },
        PhaseChain {
            phase: Phase::C,
            coil_order: c,
        },
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn feed_motor_phase_grouping_is_coil_index_mod_3() {
        let assignments = assign_coils(18, 20);
        for a in &assignments {
            let expected = match a.coil_index % 3 {
                0 => Phase::A,
                1 => Phase::B,
                _ => Phase::C,
            };
            assert_eq!(a.phase, expected, "coil {}", a.coil_index);
        }
    }

    #[test]
    fn every_phase_gets_the_same_number_of_coils_when_divisible_by_3() {
        let assignments = assign_coils(18, 20);
        let chains = build_phase_chains(&assignments);
        for chain in &chains {
            assert_eq!(chain.coil_order.len(), 6, "{:?}", chain.phase);
        }
    }

    #[test]
    fn peel_motor_every_phase_gets_three_coils() {
        let assignments = assign_coils(9, 8);
        let chains = build_phase_chains(&assignments);
        for chain in &chains {
            assert_eq!(chain.coil_order.len(), 3, "{:?}", chain.phase);
        }
    }

    #[test]
    fn each_phases_first_coil_is_always_forward() {
        // The first coil encountered for a phase defines that phase's
        // reference angle, so it's trivially within 90 degrees of itself.
        let assignments = assign_coils(18, 20);
        for phase in [Phase::A, Phase::B, Phase::C] {
            let first = assignments.iter().find(|a| a.phase == phase).unwrap();
            assert_eq!(first.sense, WindingSense::Forward, "{phase:?}");
        }
    }

    #[test]
    fn reversed_coils_are_more_than_90_degrees_from_their_phase_reference() {
        let assignments = assign_coils(18, 20);
        let chains = build_phase_chains(&assignments);

        for chain in &chains {
            let reference = assignments
                .iter()
                .find(|a| a.coil_index == chain.coil_order[0])
                .unwrap()
                .electrical_angle_rad;

            for &coil_index in &chain.coil_order {
                let a = assignments.iter().find(|a| a.coil_index == coil_index).unwrap();
                let distance = angular_distance(reference, a.electrical_angle_rad).abs();
                match a.sense {
                    WindingSense::Forward => assert!(distance <= PI / 2.0 + 1e-9),
                    WindingSense::Reversed => assert!(distance > PI / 2.0),
                }
            }
        }
    }

    #[test]
    fn feed_motor_phase_a_has_a_mix_of_forward_and_reversed_coils() {
        // With pole_pairs=10 (poles=20) and 18 coils, phase A's coils are
        // indices 0, 3, 6, 9, 12, 15. Electrical angle = 10 * mechanical.
        let assignments = assign_coils(18, 20);
        let phase_a: Vec<_> = assignments.iter().filter(|a| a.phase == Phase::A).collect();
        let senses: Vec<_> = phase_a.iter().map(|a| a.sense).collect();

        assert!(senses.contains(&WindingSense::Forward));
        assert!(
            senses.contains(&WindingSense::Reversed),
            "expected at least one reversed coil in phase A, got {senses:?}"
        );
    }

    #[test]
    fn normalize_angle_wraps_negative_and_large_angles_into_0_to_2pi() {
        assert!((normalize_angle(-PI / 2.0) - (3.0 * PI / 2.0)).abs() < 1e-9);
        assert!((normalize_angle(2.0 * PI + 0.1) - 0.1).abs() < 1e-9);
    }

    #[test]
    fn angular_distance_is_shortest_signed_path() {
        assert!((angular_distance(0.0, PI / 4.0) - PI / 4.0).abs() < 1e-9);
        // Going from a small angle to just past 2*PI wrapping to 0 should be
        // a small positive step, not almost a full revolution.
        assert!((angular_distance(0.1, 2.0 * PI - 0.1) - (-0.2)).abs() < 1e-9);
    }
}
